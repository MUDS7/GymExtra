"""Extract export-only English action names from the source workbook."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parent.parent
WORKBOOK = ROOT / "训记_动作库_分类及媒体对应_图片路径已更新.xlsx"
NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def cell_text(cell, shared):
    if cell.get("t") == "inlineStr":
        return "".join(node.text or "" for node in cell.findall(".//s:t", NS))
    value = cell.find("s:v", NS)
    if value is None:
        return ""
    return shared[int(value.text)] if cell.get("t") == "s" else value.text or ""


with ZipFile(WORKBOOK) as archive:
    shared = []
    if "xl/sharedStrings.xml" in archive.namelist():
        shared = [
            "".join(node.text or "" for node in item.findall(".//s:t", NS))
            for item in ET.fromstring(archive.read("xl/sharedStrings.xml"))
        ]
    rows = ET.fromstring(archive.read("xl/worksheets/sheet1.xml")).findall("s:sheetData/s:row", NS)
    header = {"".join(filter(str.isalpha, cell.get("r"))): cell_text(cell, shared) for cell in rows[0]}
    assert header["P"] == "英文名", "The workbook English-name column has changed"
    names = {}
    total = 0
    for row in rows[1:]:
        cells = {"".join(filter(str.isalpha, cell.get("r"))): cell_text(cell, shared).strip() for cell in row}
        if not cells.get("B"):
            continue
        total += 1
        if cells.get("P"):
            names[cells["B"]] = cells["P"]

target = ROOT / "miniprogram/data/action-english-names.js"
target.write_text(
    "// Generated by scripts/generate-action-english-names.py; keyed by workbook source ID.\n"
    + "module.exports = " + json.dumps(names, ensure_ascii=False, indent=2) + ";\n",
    encoding="utf-8",
)
print(f"Extracted {len(names)} English names from {total} actions.")
